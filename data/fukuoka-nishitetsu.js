// 니시테츠(西鉄) 전철 — 다자이후 가는 길. **손으로 적은 데이터다**(생성기 없음).
//
// 왜 손으로 넣는가: 니시테츠는 GTFS 를 공개하지 않는다. 일본 GTFS 저장소(api.gtfs-data.jp)
// 전국 597개 피드에도, GitHub 에도 없다. 후쿠오카현 피드 40개는 전부 시·정촌 커뮤니티버스다.
// 그런데 다자이후는 게임의 주요 관광지(의뢰 f2 의 필수 코스)이고, 지하철역에서 11.6km 라
// 그냥 두면 travel() 이 버스 접근으로 환산해 98분을 낸다 — 실제로는 35분쯤이다.
//
// 출처: 니시테츠 공식 시각표·노선도(https://www.nishitetsu.jp/train/). 공개된 운행 정보다.
//   소요시간은 급행·보통의 실제 표정시간에서 잡았고, 거리는 역 좌표로 잰 직선거리다
//   (subway.gap 의 첫 값은 index.html 이 안 쓴다 — 소요초만 쓴다).
//
// 담는 범위: 텐진에서 다자이후까지 실제로 타는 두 노선만.
//   천신오무타선은 후쿠오카(텐진)~오무타 74.8km 에 역이 40개가 넘지만, 게임 장소가 걸리는
//   구간은 텐진~후츠카이치뿐이라 그 사이 급행 정차역만 담는다. 완행 소역까지 넣으면
//   경로 탐색이 느려지기만 하고 결과는 같다.
//
// 지하철(data/fukuoka-subway.js)과 같은 subway 구조에 합쳐 넣는다 — subwayPath 가
// lines/pos/gap 을 그대로 읽으므로 노선을 더하는 것만으로 환승까지 풀린다.
// 니시테츠 텐진역과 지하철 텐진역은 지하로 이어져 있어 같은 "텐진" 으로 두면
// 환승이 자동으로 잡힌다(실제로도 걸어서 갈아탄다).
window.REGIONS = window.REGIONS || {};
(function () {
  const SW = REGIONS.fukuoka.subway;
  if (!SW) { console.warn('fukuoka-subway.js 를 먼저 읽어야 한다'); return; }

  // ── 천신오무타선(급행 정차역만) · 다자이후선
  // 텐진~후츠카이치 급행 17분. 사이의 급행 정차는 야쿠인·니시테츠오고리 방면이지만
  // 게임에 쓰이는 건 양 끝이라 중간역은 실제 급행 정차역인 야쿠인·미나미후쿠오카만 둔다.
  SW.lines.push(
    { id: '天神大牟田線', name: '천신오무타선', color: '#e60012',
      st: ['텐진', '니시테츠야쿠인', '미나미후쿠오카', '니시테츠후츠카이치'] },
    { id: '太宰府線', name: '다자이후선', color: '#e95504',
      st: ['니시테츠후츠카이치', '니시테츠고조', '다자이후'] },
  );

  // 역 좌표 [위도, 경도] — 실제 역 위치
  Object.assign(SW.pos, {
    '니시테츠야쿠인': [33.583600, 130.403200],
    '미나미후쿠오카': [33.532800, 130.451900],
    '니시테츠후츠카이치': [33.495200, 130.521800],
    '니시테츠고조': [33.508900, 130.523400],
    '다자이후': [33.516200, 130.528800],
  });
  // 참고: '텐진' 은 지하철 공항선에 이미 있다(같은 이름으로 두어 환승이 잡힌다).

  // 역간 [거리km, 소요초]. i번째가 st[i-1] → st[i] 구간이다.
  // 급행 기준: 텐진~후츠카이치 17분, 다자이후선 5분.
  // subwayPath 가 구간마다 DWELL(25초)을 더하므로 그만큼 빼서 적는다 —
  // 급행은 중간역을 통과해 실제로는 정차하지 않는다. 3구간이면 75초를 덜어낸다.
  SW.gap['天神大牟田線'] = [[1.3, 155], [6.2, 400], [8.4, 345]];   // 합 900초 + DWELL 75 = 16.3분
  SW.gap['太宰府線'] = [[1.6, 155], [1.0, 120]];                   // 합 275초 + DWELL 50 = 5.4분
})();
