// JR 큐다이본선 특급(유후인노모리·유후) — 유후인 가는 길. **손으로 적은 데이터다**(생성기 없음).
//
// 왜 손으로 넣는가: 유후인은 후쿠오카 시내에서 100km 라 직선 근사로는 버스 5시간이 나온다.
// 실제로는 하카타에서 특급 한 번, 2시간 10분이다. 다자이후(fukuoka-nishitetsu.js)와 같은
// 방식으로 subway 구조에 노선을 더해 subwayPath 가 환승까지 풀게 한다.
//
// 출처: JR 큐슈 공식 시각표(https://www.jrkyushu.co.jp/). 공개된 운행 정보다.
//   특급 정차역 중 게임 장소가 걸리는 하카타·구루메·히타·유후인만 담는다 — 완행 소역까지
//   넣으면 탐색만 느려지고 결과는 같다. 거리는 JR 영업거리.
//
// 한계: 특급은 하루 7~8왕복이라 실제 배차 간격이 지하철과 다르지만, travel() 의 대기 모델은
//   수단별 고정값(지하철 4+2분)이다 — 소요시간 축은 실측, 대기 축은 근사로 남는다.
window.REGIONS = window.REGIONS || {};
(function () {
  const SW = REGIONS.fukuoka.subway;
  if (!SW) { console.warn('fukuoka-subway.js 를 먼저 읽어야 한다'); return; }

  SW.lines.push(
    // 특급 유후는 유후인에서 오이타를 돌아 벳푸까지 간다 — 유후인→벳푸 구간도 실제 경로다.
    { id: '久大本線', name: 'JR 특급 유후', color: '#00a650',
      st: ['하카타', '구루메', '히타', '유후인', '벳푸'] },
    // 벳푸 직행은 소닉이 훨씬 빠르다(고쿠라 경유 약 2시간). 가메가와는 지옥순례 최근접역.
    { id: '日豊本線', name: 'JR 특급 소닉', color: '#0072bc',
      st: ['하카타', '고쿠라', '가메가와', '벳푸'] },
  );
  // '하카타' 는 지하철 공항선에 이미 있다 — 같은 이름이라 환승이 자동으로 잡힌다.
  Object.assign(SW.pos, {
    '구루메':   [33.3167, 130.5350],
    '히타':     [33.3247, 130.9236],
    '유후인':   [33.2680, 131.3545],
    '벳푸':     [33.2783, 131.5006],
    '고쿠라':   [33.8869, 130.8829],   // bounds 밖이지만 경로 계산에만 쓰여 무해하다
    '가메가와': [33.3245, 131.4869],
  });
  // 역간 [거리km, 소요초]. subwayPath 가 구간마다 DWELL(25초)을 더하므로 그만큼 빼서 적는다.
  SW.gap['久大本線'] = [[35.7, 2075], [47.6, 2600], [37.4, 3050], [33.9, 3300]];  // 하카타→유후인 130분, →벳푸 +56분
  SW.gap['日豊本線'] = [[67.2, 2675], [100.9, 4140], [5.9, 360]];                 // 하카타→벳푸 소닉 약 2시간
})();
